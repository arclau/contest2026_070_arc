#!/usr/bin/env python3
"""Import approved-for-review pet PNGs and generate the app's action table.

No image modification, simulator use, firmware build or publication. Frame order,
durations and hold semantics come from the production plan and selected clip.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'project_docs/specs/pet/redesign-20261029'
APP=ROOT/'vendor/allwinnertech/apps/luncher_dm'
DESTINATIONS=[APP/'assets/pet',
    ROOT/'vendor/allwinnertech/lichee/board/r528s3/ynm3000_nand/data/res/pet',
    ROOT/'vendor/openvela/boards/vela/prebuilts/data/pet']
LABELS=['待机','眨眼','看过来','贴贴','伸懒腰','入睡','睡觉','醒来','吃饭',
    '舔爪','开心','肚子饿','散步','起身','坐下','聆听','思考','说话']

def sha(data):return hashlib.sha256(data).hexdigest()
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    plan=json.loads((BASE/'actions.plan.json').read_text())
    production=json.loads((BASE/'production-manifest.json').read_text())
    selected=json.loads((BASE/'app-selection.json').read_text())
    originals={a['id']:a for a in production['actions']}
    assets={};actions=[];slots=0
    for i,a in enumerate(plan['actions']):
        clip_path=BASE/selected.get('clip_overrides',{}).get(a['id'],a['source_clip'])
        clip=json.loads(clip_path.read_text())
        assert clip['runtime_canvas']==[320,320] and clip['anchor_px']==[160,288]
        frames=[]
        for j,f in enumerate(clip['frames']):
            overridden=a['id'] in selected.get('clip_overrides',{})
            path=BASE/(clip['runtime_pattern'].format(index=j) if overridden else originals[a['id']]['files'][j]['file'])
            raw=path.read_bytes();digest=sha(raw)
            if not overridden:assert digest==originals[a['id']]['files'][j]['sha256']
            with Image.open(path) as im:
                assert im.mode=='RGBA' and im.size==(320,320)
                bbox=im.getchannel('A').getbbox()
                assert bbox and 0<bbox[0]<bbox[2]<320 and 0<bbox[1]<bbox[3]<320
            if digest not in assets:assets[digest]=dict(id=len(assets),file=digest+'.png',bytes=len(raw),raw=raw)
            assert 0<f['duration_ms']<=65535
            frames.append(dict(asset=assets[digest]['id'],duration_ms=f['duration_ms']))
        assert len(frames)==a['frame_count']
        actions.append(dict(id=a['id'],label=LABELS[i],frames=frames,playback=clip.get('playback',a['playback']),
            hold_frame=clip.get('hold_frame',0),release_start_frame=clip.get('release_start_frame',0),
            priority=a['priority'],start_pose=clip.get('start_pose',a['start_pose']),
            end_pose=clip.get('end_pose',a['end_pose']),source_clip=str(clip_path.relative_to(BASE))))
        slots+=len(frames)
    assert len(actions)==18 and slots==149
    entries=[dict(sha256=k,**{p:v for p,v in a.items() if p!='raw'}) for k,a in assets.items()]
    manifest=dict(schema_version=1,frame_slots=slots,unique_pngs=len(assets),actions=actions,assets=entries,
        resource_canvas=[320,320],display_canvas=[256,256],anchor_px=[160,288],
        visual_approval=False,hardware_verified=False,selection=selected)
    revision=sha(json.dumps(manifest,ensure_ascii=False,sort_keys=True).encode())[:16]
    manifest['revision']=revision
    header='''/* Generated by import_pet_actions.py; edit production clips, not this file. */
#ifndef DM_PET_ACTIONS_H
#define DM_PET_ACTIONS_H
#include <stdbool.h>
#include <stdint.h>
#define PET_FRAME_SIZE 320
#define PET_FRAME_BYTES (320u * 320u * 4u)
typedef enum {\n'''
    header+=''.join('    PET_ACTION_'+a['id'].upper()+',\n' for a in actions)
    header+='''    PET_ACTION_COUNT
} pet_action_t;
typedef enum { PET_PLAY_ONCE, PET_PLAY_LOOP, PET_PLAY_HELD } pet_play_mode_t;
typedef struct { uint16_t asset; uint16_t duration_ms; } pet_action_frame_t;
typedef struct {
    const char *name;
    const char *label;
    const pet_action_frame_t *frames;
    uint32_t duration_ms;
    uint16_t frame_count;
    uint8_t mode;
    uint8_t hold_frame;
    uint8_t release_start_frame;
    uint8_t priority;
} pet_action_clip_t;
extern const pet_action_clip_t g_pet_actions[PET_ACTION_COUNT];
extern const char *const g_pet_asset_files[];
extern const unsigned g_pet_asset_count;
extern const char g_pet_resource_revision[];
#endif
'''
    source='/* Generated by import_pet_actions.py; 320px PNG action data. */\n#include "pet_actions.h"\n'
    for a in actions:
        source+='static const pet_action_frame_t f_'+a['id']+'[] = {\n'
        source+=''.join('    {%d, %d},\n'%(f['asset'],f['duration_ms']) for f in a['frames'])+'};\n'
    source+='const pet_action_clip_t g_pet_actions[PET_ACTION_COUNT] = {\n'
    modes={'once':'PET_PLAY_ONCE','loop':'PET_PLAY_LOOP','while_held':'PET_PLAY_HELD'}
    for a in actions:
        source+='    [PET_ACTION_%s] = {"%s", "%s", f_%s, %du, %d, %s, %d, %d, %d},\n'%(a['id'].upper(),a['id'],a['label'],a['id'],sum(f['duration_ms'] for f in a['frames']),len(a['frames']),modes[a['playback']],a['hold_frame'],a['release_start_frame'],a['priority'])
    source+='};\nconst char *const g_pet_asset_files[] = {\n'
    source+=''.join('    "%s",\n'%a['file'] for a in assets.values())+'};\n'
    source+='const unsigned g_pet_asset_count = %du;\nconst char g_pet_resource_revision[] = "%s";\n'%(len(assets),revision)
    outputs={APP/'pet_actions.h':header.encode(),APP/'pet_actions.c':source.encode()}
    for dest in DESTINATIONS:
        outputs[dest/'manifest.json']=(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode()
        outputs[dest/'revision']=(revision+'\n').encode()
        for a in assets.values():outputs[dest/a['file']]=a['raw']
    for path,data in outputs.items():
        if args.check:
            assert path.is_file() and path.read_bytes()==data, 'Import differs: '+str(path)
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            if path.exists() and path.suffix=='.png':assert path.read_bytes()==data,'Refusing asset overwrite'
            else:path.write_bytes(data)
    print(json.dumps(dict(check_only=args.check,actions=len(actions),slots=slots,unique_pngs=len(assets),
        png_bytes=sum(a['bytes'] for a in assets.values()),revision=revision,destinations=[str(p.relative_to(ROOT)) for p in DESTINATIONS]),ensure_ascii=False))
if __name__=='__main__':main()
