#!/usr/bin/env python3
"""Generate pet_png_crc.h: expected size/CRC32 of every pet PNG asset.

The table lets the board report whether the bytes it read from /resource match
the shipped file, without any extra tooling on the target. Order and count come
from g_pet_asset_files[] in pet_actions.c; content comes from assets/pet.

No build, no device access, no image modification.
"""
import argparse
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / 'vendor/allwinnertech/apps/luncher_dm'
ACTIONS = APP / 'pet_actions.c'
ASSETS = APP / 'assets/pet'
OUT = APP / 'pet_png_crc.h'


def asset_names():
    text = ACTIONS.read_text(encoding='utf-8')
    match = re.search(r'g_pet_asset_files\[\] = \{(.*?)\};', text, re.S)
    if not match:
        sys.exit('g_pet_asset_files[] not found in %s' % ACTIONS)
    names = re.findall(r'"([0-9a-f]{64}\.png)"', match.group(1))
    if not names:
        sys.exit('no asset names parsed from %s' % ACTIONS)
    return names


def build(names):
    rows = []
    for index, name in enumerate(names):
        path = ASSETS / name
        data = path.read_bytes()
        if data[:8] != b'\x89PNG\r\n\x1a\n':
            sys.exit('%s is not a PNG' % path)
        rows.append((index, len(data), zlib.crc32(data) & 0xffffffff))
    return rows


def render(rows):
    out = [
        '/* Auto-generated by tools/gen_pet_png_crc.py - do not edit.',
        ' * Expected byte size and CRC32 (zlib/IEEE, init 0xffffffff) of every pet',
        ' * PNG as shipped in res.fex. Board logs compare what it read against this.',
        ' */',
        '#ifndef DM_PET_PNG_CRC_H',
        '#define DM_PET_PNG_CRC_H',
        '#include <stdint.h>',
        '',
        'struct pet_png_expect_s {',
        '    uint32_t size;',
        '    uint32_t crc;',
        '};',
        '',
        'static const struct pet_png_expect_s g_pet_png_expect[] = {',
    ]
    for index, size, crc in rows:
        out.append('    [%u] = { %uu, 0x%08xu },  /* asset %u */'
                   % (index, size, crc, index))
    out += [
        '};',
        '',
        '#define PET_PNG_EXPECT_COUNT %uu' % len(rows),
        '',
        '#endif /* DM_PET_PNG_CRC_H */',
        '',
    ]
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='fail instead of writing when the header is stale')
    args = parser.parse_args()

    text = render(build(asset_names()))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit('%s is stale; rerun without --check' % OUT)
        print('%s up to date' % OUT)
        return
    OUT.write_text(text, encoding='utf-8')
    print('%s written' % OUT)


if __name__ == '__main__':
    main()
